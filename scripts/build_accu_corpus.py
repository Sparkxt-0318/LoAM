#!/usr/bin/env python3
"""WP1a: write the 54 credit-issued ACCU soil projects as corpus records.

    python scripts/derive_accu_areas.py     # first
    python scripts/build_accu_corpus.py

Reads ``data/registry/accu_derived.json`` and writes
``data/registry/projects_accu_issued.yaml`` in the SAME field schema as
``data/registry/projects.yaml`` (every field ``{value, status, source,
locator}``), so ``tests/test_registry_corpus.py`` guards it identically. This
file is GENERATED - edit the scripts, not the YAML.

Scope flags (D-065). LoAM's scope lock is SOC, cropland topsoil 0-30 cm,
temperate. The register gives two things that bear on it:

* ``Project activities`` (stated). Classified by us into a land-use signal:
  ``cropland`` if any activity is cropping-specific (stubble retention,
  tillage); ``grazing_pasture`` if every activity is grazing- or
  pasture-specific; ``unresolved`` if the only activities could apply to
  either (nutrient application, legumes) or the set mixes both.
* The CEA centroid latitude (inferred, from geometry). A centroid north of the
  Tropic of Capricorn (23.44 S) is flagged ``tropical_latitude``. This is a
  GEOGRAPHIC flag, not a climate classification: D-028/D-033 established that
  an IPCC climate class needs MAP:PET, which we do not have for these sites,
  and no proxy is substituted for it here either.

A project is ``in_loam_scope: true`` only if land use is ``cropland`` AND the
latitude flag is clear. Everything else is out of scope and carries a
``scope_distance`` list naming each axis it fails on, so WP2 can report it
separately and never pool it into a headline.
"""

from __future__ import annotations

import datetime as dt
import json
import os
import sys

import yaml

REPO_ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DERIVED = os.path.join(REPO_ROOT, "data", "registry", "accu_derived.json")
OUT = os.path.join(REPO_ROOT, "data", "registry", "projects_accu_issued.yaml")

TROPIC_OF_CAPRICORN_DEG = -23.44

CROPLAND_ACTIVITIES = ("Retaining stubble", "Converting from intensive tillage")
GRAZING_PASTURE_ACTIVITIES = ("Altering the stocking rate", "Re-establishing or rejuvenating a pasture",
                              "Establishing, and permanently maintaining, a pasture")
EITHER_ACTIVITIES = ("Applying nutrients", "Using legume species")


def land_use_signal(activities: str) -> str:
    acts = [a.strip() for a in activities.split(";") if a.strip()]
    crop = any(a.startswith(CROPLAND_ACTIVITIES) for a in acts)
    graze = any(a.startswith(GRAZING_PASTURE_ACTIVITIES) for a in acts)
    if crop and not graze:
        return "cropland"
    if graze and not crop and all(a.startswith(GRAZING_PASTURE_ACTIVITIES + EITHER_ACTIVITIES) for a in acts):
        return "grazing_pasture"
    return "unresolved"


def approach_vocab(text: str) -> str:
    """Map the register's free-text approach to the corpus vocabulary.
    'Measurement-only ... direct soil sampling' is the measure-and-remeasure
    case (VM0042 QA2's analogue): the audit's sampling-only n_req applies
    without the QA1 upper-bound qualification. 'Hybrid ... model predictions'
    is measure-and-model."""
    t = text.lower()
    if "measurement-only" in t or "measurement only" in t:
        return "measure_and_remeasure"
    if "model" in t:
        return "measure_and_model"
    raise ValueError(f"unrecognised approach text {text!r}; extend approach_vocab rather than guessing")


def build() -> dict:
    with open(DERIVED, encoding="utf-8") as fh:
        derived = json.load(fh)
    reg = derived["register"]
    accessed = dt.date.fromisoformat(reg["accessed"][:10])
    projects = []
    for pid, r in sorted(derived["projects"].items()):
        lu = land_use_signal(r["activities"])
        lat = r["cea_centroid_lon_lat"][1]
        tropical = lat > TROPIC_OF_CAPRICORN_DEG
        distance = []
        if lu != "cropland":
            distance.append(f"land_use:{lu}")
        if tropical:
            distance.append(f"tropical_latitude:{lat:.2f}")
        in_scope = not distance
        loc_csv = f"register row Project ID == {pid}"
        p = {
            "project_id": pid,
            "project_name": r["project_name"],
            "registry": "Australian ACCU Scheme (Clean Energy Regulator)",
            "protocol": r["method"],
            "developer": r["proponent"],
            "in_loam_scope": in_scope,
            "scope_distance": distance,
            "scope_note": (
                "GENERATED by scripts/build_accu_corpus.py (D-065). Land use is our "
                f"classification of the stated activities ({lu}); latitude flag is from the "
                f"CEA centroid ({lat:.2f}), a geographic flag, not an IPCC climate class."
            ),
            "disclosure_tier": 4,
            "geography": {"value": f"{r['state']}, postcode {r['postcode']}", "status": "stated",
                          "source": "cer_register_csv", "locator": f"{loc_csv}; Project location, Project location (postcode)"},
            "practices": {"value": r["activities"], "status": "stated", "source": "cer_register_csv",
                          "locator": f"{loc_csv}; Project activities"},
            "land_use_signal": {"value": lu, "status": "inferred", "source": "cer_register_csv",
                                "locator": f"{loc_csv}; Project activities",
                                "note": "our classification of the stated activity list; rules in scripts/build_accu_corpus.py"},
            "crediting_period": {"value": f"{r['crediting_start']} to {r['crediting_end']}", "status": "stated",
                                 "source": "cer_register_csv", "locator": f"{loc_csv}; Crediting period start/end date"},
            "permanence_period_years": {"value": int(r["permanence_period"]), "status": "stated",
                                        "source": "cer_register_csv", "locator": f"{loc_csv}; Nominated Permanence Period"},
            "credits_issued": {"value": int(r["accus_total"]), "units": "ACCUs", "status": "stated",
                               "source": "cer_register_csv", "locator": f"{loc_csv}; ACCUs Total units issued"},
            "issuance_by_financial_year": {"value": {k: int(v) for k, v in r["issuance_by_fy"].items()}, "units": "ACCUs",
                                           "status": "stated", "source": "cer_register_csv",
                                           "locator": f"{loc_csv}; KACCUs/NKACCUs Units Issued in Financial Year columns, summed",
                                           "note": "sums exactly to ACCUs Total units issued (asserted in derive_accu_areas.py)"},
            "area": {"value": r["cea_area_ha"], "units": "hectares", "status": "inferred",
                     "source": "cer_cea_files", "locator": f"{r['cea_url']}; geodesic area, GRS80, {r['cea_n_polygons']} polygon(s)",
                     "note": ("Carbon estimation area (the land credits are computed over). The register has NO numeric "
                              "area field; this is our computation from the published CEA shapefile (D-064). "
                              f"Project-boundary area from the KML is {r['project_area_ha']} ha; "
                              f"{r['cea_fraction_inside_project_area']:.3f} of the CEA lies inside it.")},
            "project_boundary_area_ha": {"value": r["project_area_ha"], "units": "hectares", "status": "inferred",
                                         "source": "cer_project_kml_files", "locator": f"{r['project_kml_url']}; geodesic area, GRS80",
                                         "note": "our geodesic computation from the published project-boundary KML; an upper bound on the credited area"},
            "cea_centroid_lat": {"value": lat, "status": "inferred", "source": "cer_cea_files",
                                 "locator": f"{r['cea_url']}; centroid of the CEA polygons",
                                 "note": "planar centroid of the CEA polygons in lon/lat; used only for the tropical-latitude scope flag (D-065)"},
            "credited_rate_lower_bound": {
                "value": r.get("tau_lower_mg_c_ha_y"), "units": "Mg C/ha/y (net credited)", "status": "inferred",
                "source": "cer_register_csv",
                "locator": f"{loc_csv}; ACCUs / 3.667 / CEA area / years from crediting start to 30 June of FY {r.get('last_issuance_fy')}",
                "note": ("LOWER bound on the credited rate: issuance follows the end of the reporting period, so the "
                         "elapsed time used is an upper bound (D-064). Not used by the audit, which tests the cumulative "
                         "net change ACCUs/3.667/area."),
            },
            "quantification_approach": (
                {"value": approach_vocab(r["approach_field"]),
                 "status": "stated", "source": "cer_register_csv",
                 "locator": f"{loc_csv}; Estimation or measurement approach or model = {r['approach_field']!r}"}
                if r["approach_field"] else
                {"value": None, "status": "not_disclosed", "source": "cer_register_csv",
                 "locator": f"{loc_csv}; 'Estimation or measurement approach or model' is blank"}
            ),
            "uncertainty_deduction_applied_pct": {"value": None, "status": "not_disclosed", "source": "cer_register_page",
                                                  "locator": "no such field exists in the register"},
            "all_sampling_design_fields": {"value": None, "status": "not_disclosed", "source": "cer_register_page",
                                           "locator": "no sampling-design field exists in the register; sampling plans are not published"},
            "remeasurement_interval_years": {"value": None, "status": "not_disclosed", "source": "cer_register_page",
                                             "locator": "no such field exists in the register"},
        }
        projects.append(p)
    return {
        "schema_version": 1,
        "generated_by": "scripts/build_accu_corpus.py from data/registry/accu_derived.json - DO NOT HAND-EDIT",
        "register_as_at": reg.get("last_modified"),
        "register_sha256": reg.get("sha256"),
        "accessed": accessed,
        "note": (
            "Every credit-issued project under the two measurement-based ACCU soil methods (2018, 2021) - a "
            "complete count of that population, not a sample. Areas are INFERRED from published CEA "
            "shapefiles (the register has no area field)."
        ),
        "sources": {
            "cer_register_csv": {"title": "ACCU Scheme project register (CSV)", "url": reg.get("url"),
                                 "last_modified": reg.get("last_modified"), "sha256": reg.get("sha256"),
                                 "accessed": accessed},
            "cer_register_page": {"title": "ACCU project and contract register (landing page)",
                                  "url": "https://cer.gov.au/markets/reports-and-data/accu-project-and-contract-register",
                                  "accessed": dt.date(2026, 8, 12)},
            "cer_cea_files": {"title": "Carbon Estimation Area mapping files (zipped shapefiles), one per project",
                              "url": "https://cer.gov.au/sites/default/files/projectFiles/<ProjectID>_CEA.zip",
                              "manifest": "data/registry/cer_manifest.json (sha256 and access time per file)",
                              "accessed": accessed},
            "cer_project_kml_files": {"title": "Project mapping files (KML), one per project",
                                      "url": "https://cer.gov.au/sites/default/files/projectFiles/<ProjectID>.kml",
                                      "manifest": "data/registry/cer_manifest.json",
                                      "accessed": accessed},
        },
        "projects": projects,
    }


def main() -> int:
    data = build()
    with open(OUT, "w", encoding="utf-8") as fh:
        fh.write("# GENERATED by scripts/build_accu_corpus.py - do not hand-edit. See D-064, D-065.\n")
        yaml.safe_dump(data, fh, sort_keys=False, allow_unicode=True, width=110)
    n_in = sum(p["in_loam_scope"] for p in data["projects"])
    print(f"wrote {OUT}: {len(data['projects'])} projects, {n_in} in LoAM scope")
    from collections import Counter
    print(Counter(tuple(p["scope_distance"]) and p["scope_distance"][0].split(':')[0] + ('+lat' if len(p['scope_distance']) > 1 else '') or 'in_scope' for p in data["projects"]))
    print(Counter(p["land_use_signal"]["value"] for p in data["projects"]))
    return 0


if __name__ == "__main__":
    sys.exit(main())
